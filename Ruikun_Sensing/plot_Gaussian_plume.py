"""
plot_Gaussian_plume.py

Simple visualization of the Gaussian plume generated by ParticleClass.Particle.
The plot style follows the paper's global-fit code (viridis heatmap with a red source marker,
bold (a)/(b)/(c) panel labels, dotted gray source lines, dpi 150).

    (a) concentration map at the UAV height
    (b) downwind profile along the source y
    (c) crosswind profile at x = CROSSWIND_X
"""

import numpy as np
import matplotlib.pyplot as plt

from ParticleClass import Particle

# ------------------------------------------------------------------
# CONFIG
# ------------------------------------------------------------------
NX, NY = 200, 200                # 1 m cells, so the narrow near-source plume is resolved
XMIN, XMAX = 0, 200
YMIN, YMAX = 0, 200
SOURCE_XY = (50, 100)
Q = 0.0349                       # emission rate [g/s] (controlled-release rate in the paper)
MEAS_Z = 5.0                     # UAV measurement height [m]
WIND = np.array([1.0, 0.0])      # wind vector [u, v] [m/s]; air moves toward +x
CROSSWIND_X = 100                # x location of the crosswind profile [m]
CROSSWIND_HALF_WIDTH = 30        # crosswind profile spans source y +/- this [m]


# ------------------------------------------------------------------
# Plume evaluation (uses Particle as is)
# ------------------------------------------------------------------
def build_plume_field(particle, xvals, yvals, z=MEAS_Z, wind=WIND):
    """Concentration [ppm] on the grid, field[i, j] at (xvals[i], yvals[j])."""
    field = np.zeros((len(xvals), len(yvals)))
    for i, x in enumerate(xvals):
        for j, y in enumerate(yvals):
            field[i, j] = particle.getTrueOutput(np.array([x, y, z]), wind)  # g/m^3
    return field


def downwind_profile(particle, n=400, z=MEAS_Z, wind=WIND):
    """Concentration [ppm] along y = source y. Evaluated on a fine line, not read from the
    grid, so the profile passes exactly through the plume centerline."""
    xv = np.linspace(XMIN, XMAX, n)
    c = [particle.getTrueOutput(np.array([x, SOURCE_XY[1], z]), wind) for x in xv]
    return xv, np.array(c)


def crosswind_profile(particle, x_probe, n=400, z=MEAS_Z, wind=WIND):
    """Concentration [ppm] along y at x = x_probe, around the source y."""
    yv = np.linspace(SOURCE_XY[1] - CROSSWIND_HALF_WIDTH, SOURCE_XY[1] + CROSSWIND_HALF_WIDTH, n)
    c = [particle.getTrueOutput(np.array([x_probe, y, z]), wind) for y in yv]
    return yv, np.array(c)


# ------------------------------------------------------------------
# Plot
# ------------------------------------------------------------------
def plot_gaussian_plume(particle, save_path="plume_visualization.png",
                        label_fontsize=20, tick_fontsize=18, cbar_fontsize=18,
                        panel_label_fontsize=24):
    xvals = np.linspace(XMIN, XMAX, NX, endpoint=False) + (XMAX - XMIN) / NX / 2
    yvals = np.linspace(YMIN, YMAX, NY, endpoint=False) + (YMAX - YMIN) / NY / 2
    field = build_plume_field(particle, xvals, yvals)
    extent = [XMIN, XMAX, YMIN, YMAX]

    fig, (ax0, ax1, ax2) = plt.subplots(1, 3, figsize=(24, 6.5))

    # ---- (a) concentration map ----
    im0 = ax0.imshow(field.T, extent=extent, origin="lower", aspect="auto", cmap="viridis")
    ax0.scatter([SOURCE_XY[0]], [SOURCE_XY[1]], c="red", marker="x", s=80)
    ax0.set_xlabel("x [m] (downwind)", fontsize=label_fontsize)
    ax0.set_ylabel("y [m] (crosswind)", fontsize=label_fontsize)
    ax0.tick_params(axis="both", labelsize=tick_fontsize)
    cb0 = plt.colorbar(im0, ax=ax0, fraction=0.046)
    cb0.ax.tick_params(labelsize=cbar_fontsize)
    cb0.set_label("concentration [ppm]", fontsize=cbar_fontsize)
    ax0.text(0.04, 0.95, "(a)", transform=ax0.transAxes, fontsize=panel_label_fontsize,
             fontweight="bold", va="top", color="white")

    # ---- (b) downwind profile ----
    xv, prof_dw = downwind_profile(particle)
    ax1.plot(xv, prof_dw, "-", lw=2, color="tab:blue")
    ax1.axvline(SOURCE_XY[0], color="gray", linestyle=":", alpha=0.5)
    ax1.set_xlabel("x [m]", fontsize=label_fontsize)
    ax1.set_ylabel("concentration [ppm]", fontsize=label_fontsize)
    ax1.tick_params(axis="both", labelsize=tick_fontsize)
    ax1.grid(alpha=0.3)
    ax1.text(0.02, 0.95, "(b)", transform=ax1.transAxes, fontsize=panel_label_fontsize,
             fontweight="bold", va="top")

    # ---- (c) crosswind profile ----
    yv, prof_cw = crosswind_profile(particle, CROSSWIND_X)
    ax2.plot(yv, prof_cw, "-", lw=2, color="tab:blue")
    ax2.axvline(SOURCE_XY[1], color="gray", linestyle=":", alpha=0.5)
    ax2.set_xlabel("y [m]", fontsize=label_fontsize)
    ax2.set_ylabel("concentration [ppm]", fontsize=label_fontsize)
    ax2.tick_params(axis="both", labelsize=tick_fontsize)
    ax2.grid(alpha=0.3)
    ax2.text(0.02, 0.95, "(c)", transform=ax2.transAxes, fontsize=panel_label_fontsize,
             fontweight="bold", va="top")

    plt.tight_layout()
    plt.savefig(save_path, dpi=150)
    print(f"Figure saved to {save_path}")
    print(f"Peak along the downwind profile: {prof_dw.max():.3f} ppm at x = {xv[np.argmax(prof_dw)]:.1f} m "
          f"({xv[np.argmax(prof_dw)] - SOURCE_XY[0]:.1f} m downwind of the source)")


if __name__ == "__main__":
    particle = Particle(source_pos=SOURCE_XY, params=[Q, SOURCE_XY[0], SOURCE_XY[1], 0])
    plot_gaussian_plume(particle)
    plt.show()